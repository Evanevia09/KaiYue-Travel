const dictionaries: Record<AdminLocale, Record<AdminMessageKey, string>> = {
  en: adminEn,
  "zh-Hant": adminZhHant,
};

export type AdminVars = Record<string, string | number>;

export function parseAdminLocale(value: string | null | undefined): AdminLocale {
  return value === "zh-Hant" ? "zh-Hant" : "en";
}

export function isAdminMessageKey(value: string): value is AdminMessageKey {
  return Object.prototype.hasOwnProperty.call(adminEn, value);
}

export function t(locale: AdminLocale, key: AdminMessageKey, vars?: AdminVars): string {
  let out = dictionaries[locale][key] ?? adminEn[key];
  if (!vars) return out;
  for (const [name, value] of Object.entries(vars)) {
    out = out.replaceAll(`{${name}}`, String(value));
  }
  return out;
}

export function adminLocaleFromCookieHeader(cookieHeader: string | null | undefined): AdminLocale {
  if (!cookieHeader) return "en";
  const parts = cookieHeader.split(";");
  for (const part of parts) {
    const [name, ...rest] = part.trim().split("=");
    if (name === ADMIN_LOCALE_COOKIE) {
      return parseAdminLocale(decodeURIComponent(rest.join("=")));
    }
  }
  return "en";
}

export function adminLocaleFromCookies(cookies: {
  get(name: string): { value: string } | undefined;
}): AdminLocale {
  return parseAdminLocale(cookies.get(ADMIN_LOCALE_COOKIE)?.value);
}

export function adminLocaleCookie(locale: AdminLocale, secure = false): string {
  return `${ADMIN_LOCALE_COOKIE}=${locale}; Path=/; Max-Age=31536000; SameSite=Lax${secure ? "; Secure" : ""}`;
}

export function persistAdminLocale(
  locale: AdminLocale,
  storage: Pick<Storage, "setItem"> | null = null,
  cookieJar: { cookie: string } | null = null,
): string {
  const host =
    typeof globalThis.location === "object" ? globalThis.location.protocol === "https:" : false;
  const cookie = adminLocaleCookie(locale, host);
  if (cookieJar) cookieJar.cookie = cookie;
  else if (typeof document !== "undefined") document.cookie = cookie;
  try {
    (storage ?? (typeof localStorage === "undefined" ? null : localStorage))?.setItem(
      ADMIN_LOCALE_STORAGE_KEY,
      locale,
    );
  } catch {
    // Private mode or missing storage must not block the cookie.
  }
  return cookie;
}

export function prefixedLabel(
  locale: AdminLocale,
  prefix: "status" | "service" | "inquiry" | "channel" | "event" | "field",
  raw: string,
): string {
  const key = `${prefix}.${raw}`;
  if (isAdminMessageKey(key)) return t(locale, key);
  if (prefix === "status" || prefix === "service" || prefix === "inquiry" || prefix === "channel") {
    return raw.replaceAll("_", " ");
  }
  return raw.replaceAll("_", " ");
}

