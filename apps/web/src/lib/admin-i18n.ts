const ERROR_CODE_KEYS: Record<string, AdminMessageKey> = {
  VALIDATION_FAILED: "error.VALIDATION_FAILED",
  UNAUTHORIZED: "error.UNAUTHORIZED",
  FORBIDDEN: "error.FORBIDDEN",
  NOT_FOUND: "error.NOT_FOUND",
  CONFLICT: "error.CONFLICT",
  RATE_LIMITED: "error.RATE_LIMITED",
  IDEMPOTENCY_CONFLICT: "error.IDEMPOTENCY_CONFLICT",
  INVALID_TRANSITION: "error.INVALID_TRANSITION",
  UNAVAILABLE: "error.UNAVAILABLE",
};

export function localizeAdminError(
  error: { code?: string; message?: string } | undefined,
  locale: AdminLocale,
): string {
  const message = error?.message?.trim();
  if (message) {
    const exact = EXACT_ERROR_MESSAGES[message];
    if (exact) return t(locale, exact);

    const check = /^Check (.+)\.$/.exec(message);
    if (check?.[1]) {
      return t(locale, "error.checkField", { field: prefixedLabel(locale, "field", check[1]) });
    }
    const enterValid = /^Enter a valid (.+)\.$/.exec(message);
    if (enterValid?.[1]) {
      return t(locale, "error.enterValidField", {
        field: prefixedLabel(locale, "field", enterValid[1]),
      });
    }
    const enter = /^Enter a (.+)\.$/.exec(message);
    if (enter?.[1]) {
      return t(locale, "error.enterField", { field: prefixedLabel(locale, "field", enter[1]) });
    }
    const transition = /^Cannot change status from (\w+) to (\w+)\.$/.exec(message);
    if (transition?.[1] && transition[2]) {
      return t(locale, "error.invalidTransitionFromTo", {
        from: prefixedLabel(locale, "status", transition[1]),
        to: prefixedLabel(locale, "status", transition[2]),
      });
    }
  }
  if (error?.code && ERROR_CODE_KEYS[error.code]) {
    return t(locale, ERROR_CODE_KEYS[error.code]);
  }
  return t(locale, "error.generic");
}

export function localizeCaughtError(error: unknown, locale: AdminLocale): string {
  if (error && typeof error === "object") {
    const candidate = error as { code?: string; message?: string };
    return localizeAdminError(
      { code: candidate.code, message: candidate.message ?? String(error) },
      locale,
    );
  }
  return localizeAdminError({ message: String(error) }, locale);
}

export function adminDateLocale(locale: AdminLocale): string {
  return locale === "zh-Hant" ? "zh-Hant" : "en-GB";
}

export function formatAdminWhen(value: string, locale: AdminLocale = "en"): string {
  const parts = new Intl.DateTimeFormat(locale === "zh-Hant" ? "zh-Hant" : "en-GB", {
    timeZone: "Asia/Macau",
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).formatToParts(new Date(value));
  const get = (type: Intl.DateTimeFormatPartTypes) =>
    parts.find((part) => part.type === type)?.value ?? "";
  if (locale === "zh-Hant") {
    return `${get("year")}年${get("month")}月${get("day")}日 ${get("hour")}:${get("minute")}`;
  }
  return `${get("day")}/${get("month")}/${get("year")}, ${get("hour")}:${get("minute")}`;
}

